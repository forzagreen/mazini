"""The attested-verb lexicon: which root × pattern combinations are real verbs, and whether they take an object.

The engine conjugates any root with any pattern, and most such combinations are not words. This module
answers "is it a verb?" from the four root × pattern tables of جداول إحصاء الأفعال العربية (مروان البواب
ويحيى مير علم, CC BY 4.0; https://github.com/m-bakni/arabic-morphology): 24,188 verbs over 7,626 roots, each
marked لازم (intransitive), متعدٍّ (transitive) or both. No list of a living language is complete, so an
absence here means "not listed", not "not a verb"; the engine itself is never restricted by it.

    from mazini.lexicon import is_attested, lexicon_entries, lexicon_roots

    is_attested("كتب", "فعَل يفعُل")  # True
    is_attested("كتب", "افعوعل")  # False
    [e.wazn for e in lexicon_entries("كتب")]  # ['فعَل يفعُل', 'فعَل يفعِل', 'فعّل', 'فاعل', 'أفعل', 'تفعّل', 'تفاعل', 'افتعل', 'استفعل']
    transitivity("كتب", "استفعل")  # 'transitive'

The data is a compact string (~57 KB, generated by tools/gen_lexicon.py) decoded on first use; the rest of
the package does not import it.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import cache
from typing import Literal

from . import _lexicon_data as _data
from .errors import MaziniError
from .radicals import normalize_root
from .wazn import WAZN_BY_CODE, WAZN_BY_NAME

__all__ = [
    "LEXICON_INFO", "LexiconEntry", "LexiconInfo", "Transitivity", "is_attested", "lexicon_entries", "lexicon_roots",
    "transitivity",
]  # fmt: skip

Transitivity = Literal["intransitive", "transitive", "both"]
_TRANSITIVITY: tuple[Transitivity, ...] = ("intransitive", "transitive", "both")


@dataclass(frozen=True, slots=True)
class LexiconEntry:
    """One attested verb: a root, a pattern, and whether the verb takes a direct object."""

    #: The radicals as mazini normalises them, hamza as ء: "ءخذ".
    root: str
    #: The pattern name as WAZNS gives it: "فعَل يفعُل", "افتعل".
    wazn: str
    form_code: str
    #: "intransitive" (لازم), "transitive" (متعدٍّ) or "both" (used either way, depending on the sense).
    transitivity: Transitivity


@dataclass(frozen=True, slots=True)
class LexiconInfo:
    source_url: str
    source_commit: str
    source_date: str
    roots: int
    verbs: int


#: Where the data comes from and how much there is.
LEXICON_INFO = LexiconInfo(_data.SOURCE_URL, _data.SOURCE_COMMIT, _data.SOURCE_DATE, _data.ROOT_COUNT, _data.VERB_COUNT)


def _decode(table: str, n: int, wazns: tuple[str, ...], into: dict[str, tuple[LexiconEntry, ...]]) -> None:
    letter = dict(zip(_data.ROOT_CODES, _data.ROOT_LETTERS, strict=True))
    symbol = {ch: i for i, ch in enumerate(_data.SYMBOLS)}
    for line in table.split("\n"):
        if not line:
            continue
        root = "".join(letter[ch] for ch in line[:n])
        entries = []
        for ch in line[n:]:
            v = symbol[ch]
            wazn = wazns[v // 3]
            entries.append(LexiconEntry(root, wazn, WAZN_BY_NAME[wazn].form_code, _TRANSITIVITY[v % 3]))
        into[root] = tuple(entries)


@cache
def _table() -> dict[str, tuple[LexiconEntry, ...]]:
    out: dict[str, tuple[LexiconEntry, ...]] = {}
    _decode(_data.TRI, 3, _data.TRI_WAZNS, out)
    _decode(_data.QUAD, 4, _data.QUAD_WAZNS, out)
    return out


def _wazn_name(wazn: str) -> str:
    info = WAZN_BY_NAME.get(wazn) or WAZN_BY_CODE.get(wazn)
    if info is None:
        raise MaziniError("unknown_wazn", "Unknown morphological pattern (وزن صرفي): " + wazn)
    return info.wazn


@cache
def lexicon_roots() -> tuple[str, ...]:
    """Every root with at least one attested verb: the triliteral roots, then the quadriliteral, each in Arabic alphabetical order, hamza as ء."""
    return tuple(_table())


def lexicon_entries(root: str) -> list[LexiconEntry]:
    """The attested verbs of a root, in pattern order; empty if the root has none.

    `root` is written as for `conjugate` ("كتب", "ك ت ب", "أخذ"); a malformed root raises MaziniError.
    """
    return list(_table().get("".join(normalize_root(root)), ()))


def transitivity(root: str, wazn: str) -> Transitivity | None:
    """لازم / متعدٍّ / both for an attested verb, or None if the root × pattern is not listed.

    `wazn` is a pattern name or form code, as for `conjugate`; an unknown one raises MaziniError.
    """
    name = _wazn_name(wazn)
    for e in _table().get("".join(normalize_root(root)), ()):
        if e.wazn == name:
            return e.transitivity
    return None


def is_attested(root: str, wazn: str) -> bool:
    """True if the root × pattern is a listed verb."""
    return transitivity(root, wazn) is not None
