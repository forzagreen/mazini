"""The attested-verb lexicon: which root × pattern combinations are real verbs.

The engine conjugates any root with any pattern, and most such combinations are not words. This module
answers "is it a verb?" (and is it transitive?) from the four root × pattern tables of جداول إحصاء الأفعال العربية (مروان البواب
ويحيى مير علم, CC BY 4.0; https://github.com/m-bakni/arabic-morphology): 24,188 verbs over 7,626 roots. No
list of a living language is complete, so an absence here means "not listed", not "not a verb"; the engine
itself is never restricted by it.

    from mazini.lexicon import attested_wazns, is_attested, lexicon_passive, lexicon_roots, transitivity

    is_attested("كتب", "فعَل يفعُل")  # True
    is_attested("كتب", "افعوعل")  # False
    attested_wazns("كتب")  # ['فعَل يفعُل', 'فعَل يفعِل', 'فعّل', 'فاعل', 'أفعل', 'تفعّل', 'تفاعل', 'افتعل', 'استفعل']
    transitivity("جلس", "فعَل يفعِل")  # 'intransitive'
    lexicon_passive("جلس", "فعَل يفعِل")  # 'ipass'

The data is compact strings (~52 KB, generated by tools/gen_lexicon.py) decoded on first use; the rest of
the package does not import it.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import cache
from typing import Literal

from . import _lexicon_data as _data
from .chars import U
from .errors import MaziniError
from .radicals import normalize_root, vform_probably_no_passive
from .wazn import WAZN_BY_CODE, WAZN_BY_NAME, WaznInfo

__all__ = [
    "LEXICON_INFO", "LexiconInfo", "LexiconPassive", "Transitivity", "attested_wazns", "is_attested",
    "lexicon_passive", "lexicon_roots", "transitivity",
]  # fmt: skip

#: How the tables mark a verb: ل لازم, م متعدٍّ, ك both.
Transitivity = Literal["intransitive", "transitive", "both"]
#: The passive type `lexicon_passive` gives, as `conjugate`'s `passive` option takes it.
LexiconPassive = Literal["pass", "ipass", "nopass"]
_MARKS: tuple[Transitivity, ...] = ("intransitive", "transitive", "both")


@dataclass(frozen=True, slots=True)
class LexiconInfo:
    source_url: str
    source_commit: str
    source_date: str
    roots: int
    verbs: int


#: Where the data comes from and how much there is.
LEXICON_INFO = LexiconInfo(_data.SOURCE_URL, _data.SOURCE_COMMIT, _data.SOURCE_DATE, _data.ROOT_COUNT, _data.VERB_COUNT)


@dataclass(frozen=True, slots=True)
class _Entry:
    wazns: tuple[str, ...]
    marks: tuple[Transitivity, ...]


def _decode(table: str, marks: str, n: int, wazns: tuple[str, ...], into: dict[str, _Entry]) -> None:
    letter = dict(zip(_data.ROOT_CODES, _data.ROOT_LETTERS, strict=True))
    digit = {ch: i for i, ch in enumerate(_data.SYMBOLS)}
    digits = (len(wazns) + 5) // 6
    text = table.replace("\n", "")
    width = n + digits
    all_marks: list[Transitivity] = []
    for ch in marks.replace("\n", ""):
        v = digit[ch]
        all_marks += (_MARKS[v // 9], _MARKS[v // 3 % 3], _MARKS[v % 3])
    nxt = 0
    for at in range(0, len(text), width):
        rec = text[at : at + width]
        root = "".join(letter[ch] for ch in rec[:n])
        mask = 0
        for ch in rec[n:]:
            mask = (mask << 6) | digit[ch]
        listed = tuple(w for i, w in enumerate(wazns) if mask >> i & 1)
        into[root] = _Entry(listed, tuple(all_marks[nxt : nxt + len(listed)]))
        nxt += len(listed)


@cache
def _table() -> dict[str, _Entry]:
    out: dict[str, _Entry] = {}
    _decode(_data.TRI, _data.TRI_MARKS, 3, _data.TRI_WAZNS, out)
    _decode(_data.QUAD, _data.QUAD_MARKS, 4, _data.QUAD_WAZNS, out)
    return out


def _wazn_info(wazn: str) -> WaznInfo:
    info = WAZN_BY_NAME.get(wazn) or WAZN_BY_CODE.get(wazn)
    if info is None:
        raise MaziniError("unknown_wazn", "Unknown morphological pattern (وزن صرفي): " + wazn)
    return info


@cache
def lexicon_roots() -> tuple[str, ...]:
    """Every root with at least one attested verb: the triliteral roots, then the quadriliteral, each in Arabic alphabetical order, hamza as ء."""
    return tuple(_table())


def attested_wazns(root: str) -> list[str]:
    """The pattern names (as WAZNS gives them) of the root's attested verbs, in table order; empty if it has none.

    `root` is written as for `conjugate` ("كتب", "ك ت ب", "أخذ"); a malformed root raises MaziniError.
    """
    entry = _table().get("".join(normalize_root(root)))
    return list(entry.wazns) if entry else []


def is_attested(root: str, wazn: str) -> bool:
    """True if the root × pattern is a listed verb.

    `wazn` is a pattern name or form code, as for `conjugate`; an unknown one raises MaziniError.
    """
    return transitivity(root, wazn) is not None


def transitivity(root: str, wazn: str) -> Transitivity | None:
    """The transitivity the tables give a listed verb, or None if the root × pattern is not listed.

    ل is "intransitive", م "transitive", ك "both". Arguments as for `is_attested`.
    """
    info = _wazn_info(wazn)
    entry = _table().get("".join(normalize_root(root)))
    if entry is None or info.wazn not in entry.wazns:
        return None
    return entry.marks[entry.wazns.index(info.wazn)]


def lexicon_passive(root: str, wazn: str) -> LexiconPassive | None:
    """The passive a listed verb takes, from its transitivity, as `conjugate`'s `passive` option.

    A transitive verb (م or ك) has a full personal passive ("pass", ضُرِبْتُ); an intransitive one (ل) only
    the impersonal third-person masculine singular, with a prepositional complement ("ipass", جُلِسَ عَلَيْهِ),
    or none at all for the patterns that never take a passive (فعُل يفعُل, انفعل, افعلّ, افعالّ, …: "nopass").
    None if the verb is not listed, in which case `conjugate` guesses from the pattern.
    """
    t = transitivity(root, wazn)
    if t is None:
        return None
    if t != "intransitive":
        return "pass"
    info = _wazn_info(wazn)
    past = U if info.vowels is not None and info.vowels.past == "u" else ""
    return "nopass" if vform_probably_no_passive(info.verb_form, past) else "ipass"
